/** All Quran references ship with npm; load and validate only requested surahs. */
export function createBundledHafsReferenceProvider(): AyahReferenceProvider {
  const cache = new Map<number, AyahReferenceProvider>();
  return {
    resolveAyah(request, model) {
      const load = loaders[request.surah];
      if (!load) throw new Error('Invalid surah');
      let provider = cache.get(request.surah);
      if (!provider) { provider = createHafsReferenceProvider(load()); cache.set(request.surah, provider); }
      return provider.resolveAyah(request, model);
    },
  };
}
