"""Export character provenance from the same pinned g2p revision as the installed SDK.
Usage: python3 tools/export-reader-letter-maps.py /path/to/quran-g2p
"""
import hashlib
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
g2p = Path(sys.argv[1]).resolve()
reference = root / 'mobile-reference'
pin = json.loads(Path(__file__).with_name('recitation-g2p-pin.json').read_text())
for entry in pin['files']:
    data = (g2p / entry['path']).read_bytes()
    digest = hashlib.sha1(b'blob ' + str(len(data)).encode() + b'\0' + data).hexdigest()
    if digest != entry['gitBlob']:
        raise ValueError(f"Unpinned source: {entry['path']}")
sys.path.insert(0, str(g2p / 'src'))
from quran_g2p.textbank import TextBank
from quran_g2p.phonemize import phonemize
from quran_g2p.tokenlayer_tj3 import phones_to_tj3_units, INDEX

bank = TextBank.load('tanzil')
output = root / 'artifacts/letter-maps/hafs-tj3-7eeba120-v1'
output.mkdir(parents=True, exist_ok=True)
bundles = {}
count = 0
installed_references = {}
for ref in bank.refs():
    text = bank.ayah(ref)
    phones = phonemize(text, edition='tanzil', ref=ref).segments[0].phones
    if ref.surah not in installed_references:
        installed_references[ref.surah] = json.loads((reference / 'surahs' / f'{ref.surah:03}.json').read_text())
    installed = installed_references[ref.surah]
    units = []
    for index in sorted({p.word_index for p in phones}):
        part = [p for p in phones if p.word_index == index]
        tokens, first = phones_to_tj3_units([[p] for p in part], boundaries=False)
        if [INDEX[t] for t in tokens] != installed['ayahs'][str(ref.ayah)][index]:
            raise ValueError(f'Reference mismatch: {ref}')
        spans = [None] * len(tokens)
        for phone, token in zip(part, first):
            start, end = phone.src_span
            assert 0 <= start < end <= len(text)
            prior = spans[token]
            spans[token] = [min(prior[0], start), max(prior[1], end)] if prior else [start, end]
        assert all(spans)
        units.append(spans)
    bundles.setdefault(ref.surah, {})[str(ref.ayah)] = {'text': text, 'units': units}
    count += 1
assert count == 6236
version = 'hafs-tj3-7eeba120-v1'
reference_sha = hashlib.sha256((reference / 'manifest.json').read_bytes()).hexdigest()
asset = {
    'schemaVersion': 1,
    'version': version,
    'referenceSha256': reference_sha,
    'license': (reference / 'LICENSE').read_text(),
    'sourceNotice': (reference / 'SOURCE-NOTICE.md').read_text(),
    'surahs': {f'{surah:03}': ayahs for surah, ayahs in bundles.items()},
}
payload = (json.dumps(asset, ensure_ascii=False, separators=(',', ':')) + '\n').encode()
(output / 'letter-maps.json').write_bytes(payload)
manifest = {
    'version': version,
    'path': f'recitation/letter-maps/{version}/letter-maps.json',
    'bytes': len(payload),
    'sha256': hashlib.sha256(payload).hexdigest(),
    'referenceSha256': reference_sha,
    'ayahCounts': [len(bundles[surah]) for surah in range(1, 115)],
}
(output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
(root / 'src/letter-map-asset.ts').write_text(
    '// Generated by tools/export-reader-letter-maps.py; bulk data stays outside the package.\n'
    + 'export const LETTER_MAP_ASSET = ' + json.dumps(manifest, indent=2) + ' as const;\n')
print(f'Exported {count} ayahs; {len(payload) / 1024 / 1024:.2f} MiB')
print(f'S3 destination: s3://quralingo/{manifest["path"]}')
